"""Generate fictional review fixtures; no real paper, author or account is read."""
from pathlib import Path
from io import BytesIO
import base64
import html
import json
import textwrap
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
# Fixed demo strings make public screenshots reproducible and inspectable.
COMMENT_SPECS = [
    ('major', 'Record the source version before comparing exports'),
    ('minor', 'Clarify the document selection rule'),
    ('suggestion', 'Show the review workflow as a short sequence'),
    ('critical', 'Separate missing content from an empty result'),
    ('major', 'Verify every annotation has a matching comment'),
    ('minor', 'Use consistent page labels throughout the report'),
    ('suggestion', 'Include a compact reproducibility checklist'),
    ('minor', 'Explain which view is shown in the example'),
    ('major', 'Check the export without a network connection'),
    ('minor', 'Describe the limits of image based zoom'),
    ('major', 'Confirm the downloaded file has finished saving'),
    ('suggestion', 'Keep a readable copy of the complete feedback'),
]
SUMMARY = '''<h4>Summary</h4><p>This fictional document demonstrates a reproducible workflow for preserving a document review. The example follows the same page, comment and highlight structure used by the exporter. All text and images were created for this demonstration, with no real manuscript, author, account or review content.</p><h4>Strengths</h4><ul><li>The workflow keeps each comment connected to its source passage.</li><li>The complete report remains available in a single offline file.</li><li>A reader can navigate in both directions and inspect the same evidence.</li></ul><h4>Weaknesses</h4><ul><li>The selection rule and version record should be explicit.</li><li>The example should distinguish incomplete capture from an empty review.</li><li>Offline behavior should be checked after a download completes.</li></ul>'''


def page_image(number: int) -> str:
    """Draw an original demo page using only the fictional strings below."""
    image = Image.new('RGB', (960, 1344), 'white')
    draw = ImageDraw.Draw(image)
    regular = ROOT / 'viewer/assets/STIXTwoMath-Regular.ttf'
    font = lambda size: ImageFont.truetype(str(regular), size)
    draw.rectangle((70, 66, 890, 108), fill='#173e74')
    draw.text((88, 75), 'RESEARCH WORKFLOW / DEMONSTRATION', font=font(20), fill='white')
    draw.text((80, 146), 'A Reproducible Workflow', font=font(40), fill='#172b4d')
    draw.text((80, 195), 'for Document Review', font=font(40), fill='#172b4d')
    draw.text((80, 270), 'SYNTHETIC EXAMPLE - NO PERSONAL DATA', font=font(18), fill='#42658a')
    draw.line((80, 318, 880, 318), fill='#b8c9dc', width=2)
    headings = ['Document selection and version records', 'Linked comments and review evidence', 'Offline validation and reproducibility']
    draw.text((80, 348), headings[number - 1], font=font(29), fill='#172b4d')
    paragraphs = [
        'The review workflow begins with an explicit source document and a recorded version. Each saved page is associated with a stable page number so that readers can compare the same evidence later.',
        'Comments refer to specific passages in the document. A linked view helps the reader move from a highlighted passage to its feedback and return to the relevant part of the page.',
        'The exported file contains the presentation resources required for offline reading. A separate report view brings the complete feedback together without changing the source evidence.',
        'Validation checks page continuity, comment links and downloaded output. Any missing content should be identified before the export is described as complete.',
    ]
    for index, paragraph in enumerate(paragraphs):
        y = 428 + index * 180
        draw.text((80, y - 25), f'{number}.{index + 1} Workflow note', font=font(21), fill='#274d7a')
        for line in textwrap.wrap(paragraph, width=79):
            draw.text((80, y), line, font=font(22), fill='#334155')
            y += 29
    draw.line((80, 1230, 880, 1230), fill='#b8c9dc', width=2)
    draw.text((80, 1254), 'Demo document - generated by this project', font=font(18), fill='#63758a')
    draw.text((835, 1254), str(number), font=font(18), fill='#63758a')
    buffer = BytesIO()
    image.save(buffer, format='PNG')
    return 'data:image/png;base64,' + base64.b64encode(buffer.getvalue()).decode('ascii')


def make_fixture(name: str, folder: Path, css: str) -> dict:
    """Create source markup with small controllers for Report and native filtering."""
    document_id = f'demo-document-{name}'
    pages, cards = [], []
    for page in range(1, 4):
        boxes = []
        for offset in range(4):
            index = (page - 1) * 4 + offset
            severity, title = COMMENT_SPECS[index]
            cid = f'demo-{name}-comment-{index + 1:02}'
            # The annotations align to the original paragraph blocks drawn above.
            top = (428 + offset * 180) / 1344 * 100
            boxes.append(f'<div class="pdf-bbox-highlight severity-{severity}" data-comment-id="{cid}" style="left:8.333333%;top:{top:.6f}%;width:83.333333%;height:6.9%"></div>')
            body = f'<p><strong>Demonstration feedback.</strong> {html.escape(title)}. State the relevant rule clearly so that another reader can reproduce the review workflow and compare the same source passage.</p><p>For this example, record the document version, inspect the linked evidence and verify that the complete feedback remains available after saving. This is fictional review text created to demonstrate navigation and offline export.</p>'
            cards.append(f'<div class="figma-feedback-card margin-comment-card anchored-comment-card" data-margin-card-id="{cid}"><div class="comment-card-header"><div class="header-title-row"><span class="severity-badge severity-{severity}">{severity.title()}</span><h3 class="comment-summary">{title}</h3></div></div><div class="comment-body">{body}</div><div class="figma-card-footer"><span class="comment-location-footer">Page {page}</span></div></div>')
        pages.append(f'<div class="pdf-page-wrapper" data-pdf-page-wrapper="{page}" data-page-number="{page}"><img class="annotated-pdf-page-img" alt="Demo page {page}" src="{page_image(page)}">{"".join(boxes)}</div>')
    # These controllers model the source page only. The real extension produces
    # the final exported HTML used in tests and store screenshots.
    controls = '''const pane=document.querySelector('.feedback-stream-pane');const children=[...pane.childNodes];const list=document.querySelector('.detailed-feedback-list');const cards=[...document.querySelectorAll('[data-margin-card-id]')];const boxes=[...document.querySelectorAll('.pdf-bbox-highlight')].map(el=>({el,parent:el.parentElement}));const filter=document.getElementById('severity-filter');filter.addEventListener('change',()=>{const shown=cards.filter(c=>filter.value==='ALL'||c.querySelector('.severity-badge').textContent.toLowerCase()===filter.value);list.replaceChildren(...shown);for(const {el,parent} of boxes){el.remove();if(shown.some(c=>c.dataset.marginCardId===el.dataset.commentId))parent.append(el);}});let report=false;document.querySelector('.view-mode-toggle-btn').addEventListener('click',event=>{report=!report;event.currentTarget.querySelector('span').textContent=report?'View as Comments':'View as Report';if(report)pane.replaceChildren(document.createTextNode('Demo report view'));else pane.replaceChildren(...children);});'''
    content = f'''<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Exporter demo fixture</title><style>{css}</style></head><body><deepreview-root><main class="deepreview-main"><deepreview-review-viewer><header class="review-viewer-header"><div class="review-viewer-header-container"><h1 class="review-viewer-header-title">review-workflow-demo.pdf</h1><span class="review-version-switcher">Version 1</span><span class="doc-id-pill" hidden><code>{document_id}</code></span><div class="review-viewer-header-fill"></div><button class="mdc-button view-mode-toggle-btn"><span class="mdc-button__label">View as Report</span></button></div></header><div class="review-viewer-page"><div class="figma-split-workspace" style="--pat-pdf-width:640px"><div class="figma-manuscript-column"><div class="pdf-manuscript-viewport"><div class="pdf-pages-stack">{''.join(pages)}</div></div></div><div class="feedback-stream-pane"><div class="overall-summary-body">{SUMMARY}</div><select id="severity-filter"><option value="ALL">All Types</option><option value="minor">Minor</option><option value="major">Major</option></select><div class="detailed-feedback-list">{''.join(cards)}</div></div></div></div></deepreview-review-viewer></main></deepreview-root><script>{controls}</script></body></html>'''
    target = folder / f'{name}.html'
    target.write_text(content, encoding='utf-8')
    return {'name': name, 'url': f'https://research.google/deepreview/documents/{document_id}', 'path': target.relative_to(ROOT).as_posix(), 'pages': 3, 'comments': 12, 'highlights': 12}


def main() -> None:
    """Generate two fictional reviews and record their expected page/comment counts."""
    folder = ROOT / 'output/playwright/fixtures'
    folder.mkdir(parents=True, exist_ok=True)
    css = (ROOT / 'dist/deep-review-extension/viewer.css').read_text(encoding='utf-8')
    rows = [make_fixture(name, folder, css) for name in ['demo-one', 'demo-two']]
    (folder / 'index.json').write_text(json.dumps(rows, indent=2) + '\n', encoding='utf-8')
    print('Generated two fictional review fixtures; no user document was read.')


if __name__ == '__main__':
    main()
